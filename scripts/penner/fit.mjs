// Writes src/penner.ts: each of Penner's curves as easing data `curve` carries on the CPU and the
// GPU. A CSS cubic-bezier where the best one strays at most BEZIER_TOL from the function, otherwise
// `linear()` points placed until no stretch strays more than LINEAR_TOL.
// Run: node scripts/penner/fit.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { penner } from './reference.mjs';

const BEZIER_TOL = 0.003;
const LINEAR_TOL = 0.001;
const SAMPLES = 1001;

function bezierAt(x1, y1, x2, y2) {
  const cx = 3 * x1;
  const bx = 3 * (x2 - x1) - cx;
  const ax = 1 - cx - bx;
  const cy = 3 * y1;
  const by = 3 * (y2 - y1) - cy;
  const ay = 1 - cy - by;
  const x = (t) => ((ax * t + bx) * t + cx) * t;
  const y = (t) => ((ay * t + by) * t + cy) * t;
  return (u) => {
    if (u <= 0) return 0;
    if (u >= 1) return 1;
    let lo = 0;
    let hi = 1;
    let t = u;
    for (let i = 0; i < 40; i++) {
      if (x(t) < u) lo = t;
      else hi = t;
      t = (lo + hi) / 2;
    }
    return y(t);
  };
}

function worst(f, g) {
  let e = 0;
  for (let i = 0; i < SAMPLES; i++) {
    const u = i / (SAMPLES - 1);
    e = Math.max(e, Math.abs(f(u) - g(u)));
  }
  return e;
}

const clampX = (p) => [Math.min(1, Math.max(0, p[0])), p[1], Math.min(1, Math.max(0, p[2])), p[3]];

function nelderMead(cost, start, step, iters) {
  const n = start.length;
  let simplex = [start];
  for (let i = 0; i < n; i++) {
    const p = [...start];
    p[i] += step;
    simplex.push(p);
  }
  let costs = simplex.map(cost);
  for (let k = 0; k < iters; k++) {
    const order = costs.map((c, i) => [c, i]).sort((a, b) => a[0] - b[0]);
    simplex = order.map(([, i]) => simplex[i]);
    costs = order.map(([c]) => c);
    const centroid = Array.from(
      { length: n },
      (_, j) => simplex.slice(0, n).reduce((s, p) => s + p[j], 0) / n,
    );
    const at = (a) => centroid.map((c, j) => c + a * (simplex[n][j] - c));
    const r = at(-1);
    const cr = cost(r);
    if (cr < costs[0]) {
      const e = at(-2);
      const ce = cost(e);
      [simplex[n], costs[n]] = ce < cr ? [e, ce] : [r, cr];
    } else if (cr < costs[n - 1]) [simplex[n], costs[n]] = [r, cr];
    else {
      const c = at(0.5);
      const cc = cost(c);
      if (cc < costs[n]) [simplex[n], costs[n]] = [c, cc];
      else
        for (let i = 1; i <= n; i++) {
          simplex[i] = simplex[i].map((v, j) => simplex[0][j] + 0.5 * (v - simplex[0][j]));
          costs[i] = cost(simplex[i]);
        }
    }
  }
  const best = costs.indexOf(Math.min(...costs));
  return { p: simplex[best], cost: costs[best] };
}

function fitBezier(f) {
  const cost = (p) => worst(f, bezierAt(...clampX(p)));
  const seeds = [
    [0.42, 0, 1, 1],
    [0, 0, 0.58, 1],
    [0.42, 0, 0.58, 1],
    [0.5, 0, 0.75, 0],
    [0.25, 1, 0.5, 1],
    [0.36, 0, 0.66, -0.56],
    [0.34, 1.56, 0.64, 1],
    [0.68, -0.6, 0.32, 1.6],
  ];
  let best = { p: seeds[0], cost: Number.POSITIVE_INFINITY };
  for (const s of seeds) {
    let r = nelderMead(cost, s, 0.1, 400);
    r = nelderMead(cost, r.p, 0.01, 400);
    if (r.cost < best.cost) best = r;
  }
  const p = clampX(best.p).map((v) => Math.round(v * 1e5) / 1e5);
  return { p, error: worst(f, bezierAt(...p)) };
}

function fitLinear(f) {
  const round = (v) => Math.round(v * 1e6) / 1e6;
  const points = [[0, round(f(0))]];
  const split = (a, b, depth) => {
    const fa = f(a);
    const fb = f(b);
    let worstAt = -1;
    let worstErr = 0;
    for (let i = 1; i < 64; i++) {
      const x = a + ((b - a) * i) / 64;
      const err = Math.abs(f(x) - (fa + ((fb - fa) * (x - a)) / (b - a)));
      if (err > worstErr) [worstErr, worstAt] = [err, x];
    }
    if (worstErr > LINEAR_TOL * 0.9 && depth < 24) {
      split(a, worstAt, depth + 1);
      split(worstAt, b, depth + 1);
    } else points.push([round(b), round(fb)]);
  };
  split(0, 1, 0);
  const g = (u) => {
    let i = 1;
    while (i < points.length - 1 && points[i][0] < u) i++;
    const [x0, y0] = points[i - 1];
    const [x1, y1] = points[i];
    return x1 === x0 ? y1 : y0 + ((y1 - y0) * (u - x0)) / (x1 - x0);
  };
  return { points, error: worst(f, g) };
}

const out = [];
const rows = [];
for (const [name, f] of Object.entries(penner)) {
  const b = fitBezier(f);
  if (b.error <= BEZIER_TOL) {
    out.push(`  ${name}: { bezier: [${b.p.join(', ')}] },`);
    rows.push(`${name.padEnd(17)} bezier ${b.error.toFixed(5)}`);
    continue;
  }
  const l = fitLinear(f);
  out.push(`  ${name}: { linear: [${l.points.map(([x, y]) => `[${y}, ${x}]`).join(', ')}] },`);
  rows.push(
    `${name.padEnd(17)} linear ${l.error.toFixed(5)} ${String(l.points.length).padStart(4)} points (best bezier ${b.error.toFixed(5)})`,
  );
}

const src = `// Generated by scripts/penner/fit.mjs from scripts/penner/reference.mjs; edit those, not this.

/**
 * Robert Penner's easing curves, as data \`curve\` carries: a CSS cubic-bezier within ${BEZIER_TOL} of the
 * function where one fits, otherwise \`linear()\` points within ${LINEAR_TOL}. Each entry is the
 * \`Easing\` data its name stands for, for a host writing a named curve out as CSS, SMIL or Lottie.
 *
 * @category patch
 */
export const penner = {
${out.join('\n')}
} as const satisfies Record<
  PennerName,
  | { readonly bezier: readonly [number, number, number, number] }
  | { readonly linear: readonly (readonly [number, number])[] }
>;

/**
 * The name of one of Penner's easing curves, which {@link curve | \`curve\`} takes as a string.
 *
 * @category patch
 */
export type PennerName =
${Object.keys(penner)
  .map((n) => `  | '${n}'`)
  .join('\n')};
`;
const target = new URL('../../src/penner.ts', import.meta.url);
writeFileSync(target, src);
execFileSync('npx', ['biome', 'format', '--write', target.pathname], { stdio: 'ignore' });
for (const [i, r] of rows.entries())
  console.log(`${String(i + 1).padStart(2)}/${rows.length} ${r}`);
